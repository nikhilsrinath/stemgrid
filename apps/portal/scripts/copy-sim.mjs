// Copies the simulator engine and its pictures from apps/simulator into the portal (predev / prebuild).
// Nothing in apps/simulator changes; the copies are gitignored, so there is one source of truth and
// no drift: every dev start and every build takes the simulator's current files.
//   apps/simulator/src/simulator/{engine.js,engine.d.ts,markup.js,styles.js} → apps/portal/src/simulator/engine/
//   apps/simulator/public/assets/{modules,products}                         → apps/portal/public/assets/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const portal = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sim = path.join(portal, '..', 'simulator');

const engineSrc = path.join(sim, 'src', 'simulator');
const engineDst = path.join(portal, 'src', 'simulator', 'engine');
fs.mkdirSync(engineDst, { recursive: true });
for (const f of ['engine.js', 'engine.d.ts', 'markup.js', 'styles.js']) {
  const from = path.join(engineSrc, f);
  if (!fs.existsSync(from)) { console.error(`copy-sim: missing ${from}`); process.exit(1); }
  fs.copyFileSync(from, path.join(engineDst, f));
}
fs.writeFileSync(path.join(engineDst, 'README.md'), 'Generated by scripts/copy-sim.mjs from apps/simulator/src/simulator. Do not edit: change the simulator app instead.\n');

for (const dir of ['modules', 'products']) {
  const from = path.join(sim, 'public', 'assets', dir);
  const to = path.join(portal, 'public', 'assets', dir);
  fs.rmSync(to, { recursive: true, force: true });
  fs.cpSync(from, to, { recursive: true });
}
console.log('copy-sim: simulator engine and assets copied into apps/portal');
